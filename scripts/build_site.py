#!/usr/bin/env python3
"""
Build step for the China1 site.

1. Reads data/*.json and emits assets/data.js as `window.CHINA1 = {...}` so the
   site has NO runtime network dependency (works from file:// as well as Pages).
2. Validates every cross-reference: each source id used anywhere must exist in
   sources.json; every source with status 'retrieved'/'search' must have a URL;
   every internal href in the HTML pages must resolve to a real file.
3. Exits non-zero on any failure, so it can gate the publish.

External HTTP checks are NOT performed: this sandbox has no outbound network
access to the cited government hosts. That limitation is documented in
research/00-repo-review.md and on the About page rather than papered over.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
ASSETS = os.path.join(ROOT, "assets")

FILES = {
    "sources": "sources.json",
    "channels": "channels.json",
    "costs": "costs.json",
    "usForms": "usForms.json",
    "prohibited": "prohibited.json",
    "flagged": "flagged.json",
}

errors, warnings = [], []


def load():
    out = {}
    for key, fn in FILES.items():
        path = os.path.join(DATA, fn)
        with open(path, encoding="utf-8") as fh:
            out[key] = json.load(fh)
    return out


def build_data_js(data):
    os.makedirs(ASSETS, exist_ok=True)
    payload = json.dumps(data, ensure_ascii=False, indent=1)
    path = os.path.join(ASSETS, "data.js")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("/* AUTO-GENERATED by scripts/build_site.py — do not edit by hand. */\n")
        fh.write("window.CHINA1 = ")
        fh.write(payload)
        fh.write(";\n")
    return path, len(payload)


def collect_ids(data):
    """Every field named 'sources' holds a list of source ids."""
    used = set()

    def walk(node):
        if isinstance(node, dict):
            for k, v in node.items():
                if k == "sources" and isinstance(v, list):
                    used.update(x for x in v if isinstance(x, str))
                else:
                    walk(v)
        elif isinstance(node, list):
            for x in node:
                walk(x)

    walk(data)
    return used


def validate_sources(data):
    srcs = data["sources"]["sources"]
    by_id = {}
    for s in srcs:
        if s["id"] in by_id:
            errors.append(f"duplicate source id {s['id']}")
        by_id[s["id"]] = s

    used = collect_ids(data)
    for sid in sorted(used):
        if sid not in by_id:
            errors.append(f"referenced source id {sid} does not exist in sources.json")

    for s in srcs:
        if s["status"] in ("retrieved", "search") and not s.get("url"):
            errors.append(f"source {s['id']} is marked '{s['status']}' but has no URL")
        if s["status"] in ("retrieved", "search") and not s.get("url"):
            pass  # already covered above
        if s.get("url") and not re.match(r"^https?://", s["url"]):
            errors.append(f"source {s['id']} has a malformed URL: {s['url']}")

    unused = sorted(set(by_id) - used)
    for sid in unused:
        if by_id[sid].get("unused_ok"):
            continue
        warnings.append(f"source {sid} is defined but never cited")

    # integrity rule: an unverified flag must not be the sole basis of a
    # verified=true claim in costs.json
    cost_rows = data["costs"]["components"]
    for row in cost_rows:
        if row["verified"] and not row["sources"]:
            errors.append(f"cost row {row['id']} claims verified but cites no source")
        if (not row["verified"]) and str(row.get("value", "")).strip():
            errors.append(
                f"cost row {row['id']} is unverified but carries a numeric/string value "
                f"({row['value']!r}) — unverified rows must be blank"
            )
    return len(by_id), len(used)


def validate_internal_links():
    pages = [f for f in os.listdir(ROOT) if f.endswith(".html")]
    if "index.html" not in pages:
        errors.append("index.html is missing at repo root (GitHub Pages serves it)")
    checked = 0
    for page in pages:
        with open(os.path.join(ROOT, page), encoding="utf-8") as fh:
            html = fh.read()
        for href in re.findall(r'href="([^"#][^"]*)"', html):
            if href.startswith(("http://", "https://", "mailto:", "//")):
                continue
            # skip hrefs that are JS template expressions, not real paths
            if any(t in href for t in ("'", "+", "{", "}", "UI.")):
                continue
            target = href.split("#")[0].split("?")[0]
            if not target:
                continue
            checked += 1
            if not os.path.exists(os.path.join(ROOT, target)):
                errors.append(f"{page}: broken internal link -> {href}")
    return len(pages), checked


def validate_assets():
    for need in ("style.css", "app.js", "data.js"):
        if not os.path.exists(os.path.join(ASSETS, need)):
            errors.append(f"assets/{need} missing")
    for page in [f for f in os.listdir(ROOT) if f.endswith(".html")]:
        with open(os.path.join(ROOT, page), encoding="utf-8") as fh:
            html = fh.read()
        for need, label in (("assets/style.css", "stylesheet"), ("assets/app.js", "app.js")):
            if need not in html:
                errors.append(f"{page}: does not include {label} ({need})")
        if "assets/data.js" not in html:
            errors.append(f"{page}: does not include assets/data.js")
        if "<title>" not in html:
            errors.append(f"{page}: missing <title>")


def main():
    data = load()
    n_src, n_used = validate_sources(data)
    path, size = build_data_js(data)
    n_pages, n_links = validate_internal_links()
    validate_assets()

    print(f"  data.js written: {os.path.relpath(path, ROOT)} ({size/1024:.1f} KB)")
    print(f"  sources: {n_src} defined, {n_used} cited")
    print(f"  pages: {n_pages}, internal links checked: {n_links}")
    print(f"  channels: {len(data['channels']['channels'])}")
    print(f"  cost components: {len(data['costs']['components'])}")
    print(f"  US forms: {len(data['usForms']['forms'])}")
    print(f"  prohibited routes: {len(data['prohibited']['routes'])}")
    print(f"  flagged items: {len(data['flagged']['unverified_values'])} unverified + "
          f"{len(data['flagged']['source_irregularities'])} irregularities")

    for w in warnings:
        print(f"  WARN  {w}")
    if errors:
        print("\nFAILED:")
        for e in errors:
            print(f"  ERROR {e}")
        sys.exit(1)
    print("\nOK — build clean, no broken internal links, all references resolve.")


if __name__ == "__main__":
    main()
