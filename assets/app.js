/* China1 — shared UI helpers. All data comes from window.CHINA1 (assets/data.js),
   generated by scripts/build_site.py from data/*.json. No network calls at runtime. */
(function () {
  "use strict";
  var D = window.CHINA1 || {};

  var SOURCE_MAP = {};
  (D.sources && D.sources.sources || []).forEach(function (s) { SOURCE_MAP[s.id] = s; });

  function esc(s) {
    return String(s == null ? "" : s)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
  }

  /* Source chip. If the source has a URL render a link, else a muted non-link chip. */
  function srcChip(id) {
    var s = SOURCE_MAP[id];
    if (!s) return '<span class="src unverified" title="Unknown source id">' + esc(id) + "</span>";
    var cls = s.status || "unverified";
    var tip = s.title + " — " + (s.publisher || "") + " [" + cls + "]";
    if (s.url) {
      return '<a class="src ' + cls + '" href="' + esc(s.url) + '" target="_blank" rel="noopener noreferrer" title="' + esc(tip) + '">' + esc(id) + "</a>";
    }
    return '<span class="src unverified" title="' + esc(tip + " — no retrievable official URL") + '">' + esc(id) + "</span>";
  }

  function srcList(ids) {
    if (!ids || !ids.length) return '<span class="muted">—</span>';
    return '<div class="srcs">' + ids.map(srcChip).join("") + "</div>";
  }

  function badge(text, kind) { return '<span class="b ' + (kind || "neutral") + '">' + esc(text) + "</span>"; }

  var AVAIL = {
    available:   ["Available", "ok"],
    conditional: ["Conditional", "warn"],
    limited:     ["Limited", "warn"],
    "not-a-route": ["Not a route", "neutral"],
    "not-available": ["Not available", "bad"]
  };
  function availBadge(a) { var m = AVAIL[a] || [a || "—", "neutral"]; return badge(m[0], m[1]); }

  function statusBadge(st) {
    if (st === "retrieved") return badge("Verified", "ok");
    if (st === "search") return badge("Verified (excerpt)", "warn");
    return badge("Unverified", "bad");
  }

  function table(cols, rows) {
    var thead = "<thead><tr>" + cols.map(function (c) {
      return "<th" + (c.w ? ' style="min-width:' + c.w + '"' : "") + ">" + c.h + "</th>";
    }).join("") + "</tr></thead>";
    var tbody = "<tbody>" + rows.map(function (r) {
      return "<tr" + (r.attrs || "") + ">" + r.cells.map(function (c) {
        return "<td" + (c.cls ? ' class="' + c.cls + '"' : "") + ">" + c.html + "</td>";
      }).join("") + "</tr>";
    }).join("") + "</tbody>";
    return '<div class="table-wrap"><table>' + thead + tbody + "</table></div>";
  }

  function list(arr) {
    if (!arr || !arr.length) return '<span class="muted">—</span>';
    return "<ul>" + arr.map(function (x) { return "<li>" + esc(x) + "</li>"; }).join("") + "</ul>";
  }

  /* mark the active nav item */
  function markNav() {
    var here = location.pathname.split("/").pop() || "index.html";
    document.querySelectorAll(".site-nav a").forEach(function (a) {
      var target = a.getAttribute("href");
      if (target === here) a.setAttribute("aria-current", "page");
    });
  }

  document.addEventListener("DOMContentLoaded", markNav);

  window.UI = {
    esc: esc, srcChip: srcChip, srcList: srcList, badge: badge,
    availBadge: availBadge, statusBadge: statusBadge, table: table,
    list: list, SOURCE_MAP: SOURCE_MAP, D: D
  };
})();
